<?php

namespace Modules\BankSampah\Tests\Unit\Models;

use Modules\BankSampah\Tests\TestCase;

class BankSampahMemberTest extends TestCase
{
    protected function setUp(): void
    {
        parent::setUp();
        $this->createBankSampahTables();
    }

    public function test_table_name(): void
    {
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $this->assertEquals('bank_sampah_member', $model->getTable());
    }

    public function test_hidden_attributes(): void
    {
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $hidden = $model->getHidden();
        
        $this->assertContains('pin', $hidden);
    }

    public function test_uuid_is_generated_on_creation(): void
    {
        $member = $this->createMember(['uuid' => null]);
        
        // UUID should be generated by booted() method
        $this->assertNotEmpty($member->uuid);
    }

    public function test_tambah_saldo_increments_atomically(): void
    {
        $member = $this->createMember(['saldo' => 1000]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $result = $model->tambahSaldo(500);
        
        // Check database directly
        $saldo = \DB::table('bank_sampah_member')
            ->where('id', $member->id)
            ->value('saldo');
        
        $this->assertEquals(1500, $saldo);
    }

    public function test_kurangi_saldo_decrements_atomically(): void
    {
        $member = $this->createMember(['saldo' => 1000]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $result = $model->kurangiSaldo(300);
        
        $saldo = \DB::table('bank_sampah_member')
            ->where('id', $member->id)
            ->value('saldo');
        
        $this->assertEquals(700, $saldo);
    }

    public function test_kurangi_saldo_fails_when_insufficient(): void
    {
        $member = $this->createMember(['saldo' => 100]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $result = $model->kurangiSaldo(500);
        
        $this->assertFalse($result);
        
        // Saldo should remain unchanged
        $saldo = \DB::table('bank_sampah_member')
            ->where('id', $member->id)
            ->value('saldo');
        
        $this->assertEquals(100, $saldo);
    }

    public function test_tambah_poin_increments_atomically(): void
    {
        $member = $this->createMember(['poin' => 50]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $result = $model->tambahPoin(25);
        
        $poin = \DB::table('bank_sampah_member')
            ->where('id', $member->id)
            ->value('poin');
        
        $this->assertEquals(75, $poin);
    }

    public function test_tukar_poin_decrements_atomically(): void
    {
        $member = $this->createMember(['poin' => 100]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $result = $model->tukarPoin(30);
        
        $poin = \DB::table('bank_sampah_member')
            ->where('id', $member->id)
            ->value('poin');
        
        $this->assertEquals(70, $poin);
    }

    public function test_tukar_poin_fails_when_insufficient(): void
    {
        $member = $this->createMember(['poin' => 10]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $result = $model->tukarPoin(50);
        
        $this->assertFalse($result);
        
        // Poin should remain unchanged
        $poin = \DB::table('bank_sampah_member')
            ->where('id', $member->id)
            ->value('poin');
        
        $this->assertEquals(10, $poin);
    }

    public function test_generate_no_member_unique_per_desa(): void
    {
        // Create existing member
        $this->createMember(['no_member' => 'BS-00001']);
        
        // Generate new number
        $noMember = \Modules\BankSampah\Models\BankSampahMember::generateNoMember('BS');
        
        // Should be different from existing
        $this->assertNotEquals('BS-00001', $noMember);
        $this->assertStringStartsWith('BS-', $noMember);
    }

    public function test_set_pin_hashed(): void
    {
        $member = $this->createMember(['pin' => null]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $model->setPin('1234');
        
        // PIN should be hashed, not plain text
        $this->assertNotEquals('1234', $model->pin);
        $this->assertTrue(\Illuminate\Support\Facades\Hash::check('1234', $model->pin));
    }

    public function test_verify_pin_correct(): void
    {
        $hashedPin = \Illuminate\Support\Facades\Hash::make('1234');
        $member = $this->createMember(['pin' => $hashedPin]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $model->pin = $hashedPin;
        
        $this->assertTrue($model->verifyPin('1234'));
    }

    public function test_verify_pin_incorrect(): void
    {
        $hashedPin = \Illuminate\Support\Facades\Hash::make('1234');
        $member = $this->createMember(['pin' => $hashedPin]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $model->pin = $hashedPin;
        
        $this->assertFalse($model->verifyPin('5678'));
    }

    public function test_verify_pin_returns_true_when_empty(): void
    {
        $member = $this->createMember(['pin' => null]);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $model->pin = null;
        
        // Empty PIN should allow access (PIN not set yet)
        $this->assertTrue($model->verifyPin('1234'));
    }

    public function test_reset_uuid_changes_uuid(): void
    {
        $member = $this->createMember(['uuid' => 'old-uuid-1234']);
        
        $model = new \Modules\BankSampah\Models\BankSampahMember();
        $model->id = $member->id;
        $model->uuid = 'old-uuid-1234';
        
        $newUuid = $model->resetUuid();
        
        $this->assertNotEquals('old-uuid-1234', $newUuid);
        $this->assertNotEmpty($newUuid);
    }

    public function test_lokasi_relationship(): void
    {
        $member = new \Modules\BankSampah\Models\BankSampahMember();
        $relation = $member->lokasi();
        
        $this->assertInstanceOf(\Illuminate\Database\Eloquent\Relations\BelongsTo::class, $relation);
    }

    public function test_transaksi_relationship(): void
    {
        $member = new \Modules\BankSampah\Models\BankSampahMember();
        $relation = $member->transaksi();
        
        $this->assertInstanceOf(\Illuminate\Database\Eloquent\Relations\HasMany::class, $relation);
    }

    public function test_reward_relationship(): void
    {
        $member = new \Modules\BankSampah\Models\BankSampahMember();
        $relation = $member->reward();
        
        $this->assertInstanceOf(\Illuminate\Database\Eloquent\Relations\HasMany::class, $relation);
    }
}
